const STATUS_KEY = {
  stopped: 'statusStopped',
  starting: 'statusStarting',
  running: 'statusRunning',
  stopping: 'statusStopping',
  crashed: 'statusCrashed',
  failed: 'statusFailed',
} as const satisfies Record<RunStatus, Parameters<typeof t>[0]>;

/** Label status prototype dalam bahasa tray. */
export const statusLabel = (status: RunStatus): string => t(STATUS_KEY[status]);

/** Persen bulat sesuai bahasa tray (mis. progres unduhan). */
export const formatPercent = (fraction: number): string =>
  new Intl.NumberFormat(intlTag(), { style: 'percent', maximumFractionDigits: 0 }).format(fraction);

/** Nama pilihan bahasa: `auto` diterjemahkan, bahasa lain memakai namanya sendiri (mis. "English"). */
export const langName = (setting: LangSetting): string => (setting === 'auto' ? t('langAuto') : LOCALE_INFO[setting].name);
